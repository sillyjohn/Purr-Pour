-- Development schema, applied explicitly. No application startup DDL.
CREATE TABLE IF NOT EXISTS coffee_menu (
  id text PRIMARY KEY,
  data jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS coffee_pets (
  id text PRIMARY KEY,
  data jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS coffee_customers (
  id text PRIMARY KEY,
  preferences jsonb NOT NULL DEFAULT '{"selectedPet":"miso","reducedMotion":false,"soundEnabled":false}'::jsonb
);
CREATE TABLE IF NOT EXISTS coffee_orders (
  id text PRIMARY KEY,
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  owner_id text NOT NULL,
  request_id text NOT NULL,
  customer_name text NOT NULL,
  email text NOT NULL,
  status text NOT NULL CHECK (status IN ('accepted','preparing','ready','collected','cancelled')),
  total_cents integer NOT NULL CHECK (total_cents >= 0),
  practice boolean NOT NULL DEFAULT true,
  payment_status text NOT NULL DEFAULT 'practice',
  notes text NOT NULL DEFAULT '',
  lines jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(owner_id,request_id)
);
CREATE INDEX IF NOT EXISTS coffee_orders_owner_idx ON coffee_orders(owner_id,created_at DESC);
CREATE INDEX IF NOT EXISTS coffee_orders_status_idx ON coffee_orders(status,updated_at);
CREATE TABLE IF NOT EXISTS coffee_outbox (
  id text PRIMARY KEY,
  owner_id text NOT NULL,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
